namespace Platform.Domain.Entities.Enums;

/// <summary>
/// Represents the proficiency level of a language.
/// </summary>
public enum LanguageLevel
{
    /// <summary>
    /// Beginner level of language proficiency.
    /// </summary>
    Beginner = 1,

    /// <summary>
    /// Intermediate level of language proficiency.
    /// </summary>
    Intermediate = 2,

    /// <summary>
    /// Advanced level of language proficiency.
    /// </summary>
    Advanced = 3,

    /// <summary>
    /// Native or bilingual level of language proficiency.
    /// </summary>
    Native = 4,
}
