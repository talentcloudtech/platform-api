namespace Platform.Domain.Enums;

/// <summary>
/// Enum representing the different priority levels of a task.
/// </summary>
public enum TaskPriority
{
    /// <summary>
    /// Represents a task with critical priority.
    /// </summary>
    Critical = 1,

    /// <summary>
    /// Represents a task with high priority.
    /// </summary>
    High = 2,

    /// <summary>
    /// Represents a task with medium priority.
    /// </summary>
    Medium = 3,

    /// <summary>
    /// Represents a task with low priority.
    /// </summary>
    Low = 4,
}
